CREATE TABLE IF NOT EXISTS orders (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id BIGINT NOT NULL,
  qty        INTEGER NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  -- s08: ai đặt đơn (username) và địa chỉ giao hàng đã mã hoá (hex của IV ‖ bản mã ‖ tag AES-GCM).
  owner            VARCHAR(50),
  delivery_address VARCHAR(1000)
);

-- User của shop (s05). Tên bảng và cột cố định: test của lab đọc và ghi trực tiếp vào đây.
CREATE TABLE IF NOT EXISTS shop_users (
  id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username VARCHAR(50)  NOT NULL UNIQUE,
  password VARCHAR(500) NOT NULL,
  enabled  BOOLEAN      NOT NULL DEFAULT TRUE,
  locked   BOOLEAN      NOT NULL DEFAULT FALSE
);

CREATE TABLE IF NOT EXISTS shop_user_authorities (
  user_id   BIGINT      NOT NULL REFERENCES shop_users (id),
  authority VARCHAR(50) NOT NULL,
  PRIMARY KEY (user_id, authority)
);
