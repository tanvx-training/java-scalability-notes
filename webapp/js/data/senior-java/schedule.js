// Ngày theo giờ địa phương, tránh lệch múi giờ khi so với dayKey() của activity.js.
export function dateOfWeek(n, start = PLAN.start) {
  const [y, m, d] = start.split("-").map(Number);
  const from = new Date(y, m - 1, d + (n - 1) * 7);
  const to = new Date(y, m - 1, d + (n - 1) * 7 + 6);
  return { from, to };
}

function hoursFor(spec) {
  if (spec.hours) return spec.hours;
  return PLAN.hoursByKind[spec.kind] ?? PLAN.hoursByKind.year1;
}

// Nở WEEKS thành bản ghi đầy đủ. `tracksById` là Map id → track (từ roadmap.js), truyền
// vào để tệp này không import roadmap.js (check-data nạp cả hai độc lập).
export function buildSchedule(tracksById, start = PLAN.start) {
  const weekOf = (trackId, weekId) => tracksById.get(trackId)?.weeks.find((w) => w.id === weekId) ?? null;
  const expand = (refs, trackFromWeek) => (refs ?? []).map((r) => {
    // spine/project: [weekId, from, to] — track suy từ tiền tố id tuần.
    // extra: [trackId, weekId, from, to].
    const [trackId, weekId, from, to] = r.length === 4 ? r : [trackFromWeek(r[0]), r[0], r[1], r[2]];
    const week = weekOf(trackId, weekId);
    const items = week ? week.items.slice(from - 1, to).map((it) => it.id) : [];
    return { trackId, weekId, from, to, items, missing: !week };
  });
  const trackOfSpine = (weekId) => weekId.replace(/-(w\d+|done)$/, "");
  return WEEKS.map(([n, spec]) => {
    const spine = expand(spec.spine, trackOfSpine);
    const project = expand(spec.project, trackOfSpine);
    const extra = expand(spec.extra, () => null);
    const refs = [...spine, ...project, ...extra];
    const hours = hoursFor(spec);
    return {
      n,
      q: Math.ceil(n / PLAN.quarterWeeks),
      phase: spec.phase,
      kind: spec.kind,
      rest: !!spec.rest,
      focus: spec.focus,
      dates: dateOfWeek(n, start),
      spine, project, extra, refs,
      items: refs.flatMap((r) => r.items),
      reads: spec.reads ?? [],
      practice: spec.practice ?? "",
      write: spec.write ?? "",
      hours,
      hoursTotal: Object.values(hours).reduce((a, b) => a + b, 0),
      ms: spec.ms ?? null,
    };
  });
}

